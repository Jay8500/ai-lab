import { DatePipe } from '@angular/common';
import { Component, computed, inject, input } from '@angular/core';
import { LucideAngularModule } from 'lucide-angular';
import { renderMessage } from '../core/inbox.service';
import { LabService } from '../core/lab.service';
import { Visit } from '../core/models';
import { TenantService } from '../core/tenant.service';
import { Modal } from './modal';

/** AI status row on a patient card: skeleton while writing, view when ready, retry on error. */
@Component({
  selector: 'app-ai-status',
  imports: [LucideAngularModule],
  template: `
    @let v = visit();
    @switch (v.ai_status) {
      @case ('pending') {
        <div class="rounded-xl border border-violet-100 bg-violet-50/50 p-3" aria-live="polite">
          <p class="flex items-center gap-1.5 text-[11px] font-semibold text-violet-600">
            <lucide-icon name="sparkles" class="size-3.5 animate-pulse" /> Writing AI explanation…
          </p>
          <div class="mt-2 space-y-1.5">
            <div class="h-2 w-11/12 animate-pulse rounded bg-violet-100"></div>
            <div class="h-2 w-9/12 animate-pulse rounded bg-violet-100"></div>
            <div class="h-2 w-10/12 animate-pulse rounded bg-violet-100"></div>
          </div>
        </div>
      }
      @case ('done') {
        <button class="flex w-full items-center gap-2 rounded-xl border border-violet-100 bg-violet-50/60 px-3 py-2 text-left text-xs font-semibold text-violet-700 transition hover:bg-violet-50"
                (click)="lab.aiFor.set(v)">
          <lucide-icon name="sparkles" class="size-3.5" /> AI explanation ready
          <lucide-icon name="chevron-right" class="ml-auto size-3.5" />
        </button>
      }
      @case ('error') {
        <div class="rounded-xl border border-rose-100 bg-rose-50/60 px-3 py-2">
          <p class="text-[11px] leading-snug text-rose-600">{{ v.ai_error || 'AI explanation failed.' }}</p>
          <button class="mt-1.5 inline-flex items-center gap-1 text-[11px] font-bold text-violet-700 hover:underline" (click)="lab.explain(v)">
            <lucide-icon name="refresh-cw" class="size-3" /> Explain with AI
          </button>
        </div>
      }
      @default {
        <button class="btn-ghost w-full py-1.5! text-xs text-violet-700!" (click)="lab.explain(v)">
          <lucide-icon name="sparkles" class="size-3.5" /> Explain with AI
        </button>
      }
    }
  `,
})
export class AiStatus {
  readonly visit = input.required<Visit>();
  protected readonly lab = inject(LabService);
}

/** Reader for a visit's AI explanation (lab side). */
@Component({
  selector: 'app-ai-explanation',
  imports: [LucideAngularModule, DatePipe, Modal],
  template: `
    @if (current(); as v) {
      <app-modal title="AI explanation" [subtitle]="v.patient_name + ' · #' + v.token" [width]="580" (closed)="lab.aiFor.set(null)">
        @if (v.ai_status === 'pending') {
          <div class="space-y-2 py-2">
            @for (w of ['w-11/12', 'w-9/12', 'w-10/12', 'w-8/12', 'w-11/12', 'w-7/12']; track $index) {
              <div class="h-3 animate-pulse rounded bg-violet-100 {{ w }}"></div>
            }
          </div>
        } @else {
          <div class="space-y-3 text-sm leading-relaxed text-slate-600 [&_p]:m-0" [innerHTML]="html()"></div>
        }
        <p class="mt-5 flex gap-2 rounded-xl bg-amber-50/70 px-3 py-2.5 text-xs text-amber-700">
          <lucide-icon name="info" class="mt-0.5 size-3.5 shrink-0" />
          {{ tenant.pages().ai_disclaimer || 'This explanation is generated by AI for general understanding only. It is not a diagnosis. Please consult your doctor about your results.' }}
        </p>
        <div class="mt-4 flex flex-wrap items-center gap-2 border-t border-slate-100 pt-4 text-[11px] text-slate-400">
          @if (v.ai_generated_at) { <span>Generated {{ v.ai_generated_at | date: 'MMM d, h:mm a' }}</span> }
          <button class="btn-ghost ml-auto py-1.5! text-xs" (click)="lab.explain(v)" [disabled]="v.ai_status === 'pending'">
            <lucide-icon name="refresh-cw" class="size-3.5" [class.animate-spin]="v.ai_status === 'pending'" /> Regenerate
          </button>
          <button class="btn-primary py-1.5! text-xs" (click)="lab.aiFor.set(null)">Done</button>
        </div>
      </app-modal>
    }
  `,
})
export class AiExplanation {
  protected readonly lab = inject(LabService);
  protected readonly tenant = inject(TenantService);
  /** Always the live copy, so a regenerate updates in place. */
  protected readonly current = computed(() => {
    const open = this.lab.aiFor();
    return open ? (this.lab.visits().find((x) => x.id === open.id) ?? open) : null;
  });
  protected readonly html = computed(() => renderMessage(this.current()?.ai_summary ?? ''));
}
